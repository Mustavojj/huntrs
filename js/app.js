    async processWithdrawal(coinAmount, wallet) {
        if (this._withdrawLock) {
            this.showNotification('Please wait', 'You can withdraw again after 10 seconds', 'warning');
            this.vibrate('warning');
            return;
        }

        const amount = parseFloat(coinAmount);
        if (isNaN(amount) || amount <= 0) {
            this.showNotification('Error', this.t('invalid_amount'), 'error');
            this.vibrate('error');
            return;
        }

        if (!wallet || !wallet.startsWith('UQ') || wallet.length < 20) {
            this.showNotification('Error', this.t('wallet_invalid'), 'error');
            this.vibrate('error');
            return;
        }

        this._withdrawLock = true;
        setTimeout(() => { this._withdrawLock = false; }, 10000);

        const withdrawBtn = document.getElementById('withdraw-btn');
        if (withdrawBtn) {
            withdrawBtn.disabled = true;
            withdrawBtn.innerHTML = '<i class="fas fa-spinner fa-pulse"></i> Sending...';
        }

        try {
            const result = await this.fetchFromServer('/api/withdraw-gram', {
                coinAmount: amount,
                walletAddress: wallet
            });

            if (result.error) {
                this.showNotification('Error', result.error, 'error');
                this.vibrate('error');
                if (withdrawBtn) {
                    withdrawBtn.disabled = false;
                    withdrawBtn.innerHTML = this.t('confirm_withdrawal');
                }
                this._withdrawLock = false;
                return;
            }

            if (result.user) {
                this.coinBalance = result.user.coin_balance || 0;
                this.gramBalance = result.user.gram_balance || 0;
                this.updateHeaderBalances();
            }

            this.showNotification('Withdrawn!', `${result.gramAmount.toFixed(5)} GRAM sent to your wallet`, 'success');
            this.vibrate('success');

            if (this._walletLoaded) {
                this.renderWallet();
            }

            if (withdrawBtn) {
                withdrawBtn.disabled = true;
                withdrawBtn.innerHTML = '✓ Sent';
                setTimeout(() => {
                    withdrawBtn.disabled = false;
                    withdrawBtn.innerHTML = this.t('confirm_withdrawal');
                }, 5000);
            }

            this._withdrawLock = false;

        } catch (error) {
            if (withdrawBtn) {
                withdrawBtn.disabled = false;
                withdrawBtn.innerHTML = this.t('confirm_withdrawal');
            }
            this._withdrawLock = false;
        }
    }

